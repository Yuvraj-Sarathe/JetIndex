import { useState, useEffect } from 'react';
import { getApixDaily, getHeatmap, getElasticity, getBacktest, getScrapedVsDGCA } from '../api/client';

/**
 * Custom hook for fetching APIx daily data.
 */
export function useApixDaily({ from, to } = {}) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    let cancelled = false;
    setLoading(true);
    getApixDaily({ from, to })
      .then((res) => {
        if (!cancelled) {
          setData(res);
          setLoading(false);
        }
      })
      .catch((err) => {
        if (!cancelled) {
          setError(err.message);
          setLoading(false);
        }
      });
    return () => { cancelled = true; };
  }, [from, to]);

  return { data, loading, error };
}

